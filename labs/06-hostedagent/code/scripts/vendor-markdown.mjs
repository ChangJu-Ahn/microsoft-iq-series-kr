import {readFile, writeFile} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modulePath = fileURLToPath(import.meta.resolve("markdown-it/browser"));
const packageRoot = path.dirname(fileURLToPath(import.meta.resolve("markdown-it/package.json")));
const [source, license] = await Promise.all([
  readFile(modulePath, "utf8"),
  readFile(path.join(packageRoot, "LICENSE"), "utf8")
]);
await writeFile(path.join(root, "static/markdown-it.js"),
  `/* Generated by npm run build. markdown-it 15.0.2\n${license.replaceAll("*/", "* /")}\n*/\n${source}`);
console.log("Generated static/markdown-it.js from the pinned browser bundle with its MIT license.");
